import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import readline from 'node:readline';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { run } from '../src/core.mjs';

test('MCP client handshake, tool discovery, recording, reconstruction and verification', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'unmix-mcp-')); const repo = path.join(dir, 'repo'); fs.mkdirSync(repo);
  for (const args of [['init', '-q'], ['config', 'user.name', 'Test'], ['config', 'user.email', 'test@example.invalid']]) assert.equal(run(repo, 'git', args).ok, true);
  fs.writeFileSync(path.join(repo, 'base.txt'), 'base'); run(repo, 'git', ['add', '.']); run(repo, 'git', ['commit', '-qm', 'base']);
  const bin = fileURLToPath(new URL('../bin/unmix.mjs', import.meta.url));
  const child = spawn(process.execPath, [bin, 'mcp', '--repo', repo], { stdio: ['pipe', 'pipe', 'pipe'] });
  let sequence = 0; const waiting = new Map(); let stderr = '';
  child.stderr.on('data', data => stderr += data);
  readline.createInterface({ input: child.stdout }).on('line', line => {
    const response = JSON.parse(line); waiting.get(response.id)?.(response); waiting.delete(response.id);
  });
  const request = (method, params = {}) => new Promise((resolve, reject) => {
    const id = ++sequence, timer = setTimeout(() => reject(new Error('MCP timeout')), 5000);
    waiting.set(id, response => { clearTimeout(timer); resolve(response); });
    child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id, method, params }) + '\n');
  });
  const tool = async (name, args = {}) => {
    const response = await request('tools/call', { name, arguments: args });
    assert.equal(response.result?.isError, undefined, JSON.stringify(response));
    return JSON.parse(response.result.content[0].text);
  };
  t.after(() => { child.kill(); fs.rmSync(dir, { recursive: true, force: true }); });
  assert.equal((await request('tools/list')).error.code, -32000);
  const init = await request('initialize', { protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 'test-client', version: '1' } });
  assert.equal(init.result.protocolVersion, '2025-06-18');
  child.stdin.write(JSON.stringify({ jsonrpc: '2.0', method: 'notifications/initialized' }) + '\n');
  const discovery = (await request('tools/list')).result.tools;
  assert.equal(discovery.length, 14);
  assert.equal(discovery.find(t => t.name === 'unmix_report').annotations.readOnlyHint, true);
  assert.equal((await request('ping')).result.constructor, Object);
  await tool('unmix_init');
  await tool('unmix_begin', { taskId: 'drop', title: 'Drop', intent: 'Temporary file' });
  fs.writeFileSync(path.join(repo, 'drop.txt'), 'drop'); await tool('unmix_finish');
  const preview = await tool('unmix_preview', { remove: ['drop'] });
  assert.equal(discovery.find(t => t.name === 'unmix_preview').annotations.readOnlyHint, true);
  assert.equal(preview.summary.removed, 1); assert.equal(preview.tasks[0].replay, 'not_attempted');
  const previewMarkdown = await request('tools/call', { name: 'unmix_preview', arguments: { remove: ['drop'], format: 'markdown' } });
  assert.match(previewMarkdown.result.content[0].text, /# Unmix removal preview/);
  assert.equal((await request('tools/call', { name: 'unmix_preview', arguments: { remove: ['unknown'] } })).result.isError, true);
  const plan = await tool('unmix_prepare', { ...preview.next.arguments, instruction: 'Remove the temporary file', protectedFiles: ['base.txt'], checks: [['node', '-e', "if(require('fs').existsSync('drop.txt'))process.exit(1)"]] });
  assert.equal((await tool('unmix_verify', { planId: plan.planId })).passed, true);
  const report = await tool('unmix_report', { planId: plan.planId });
  assert.equal(report.checks.state, 'passed');
  assert.equal(report.removedTasks[0].taskId, 'drop');
  const markdown = await request('tools/call', { name: 'unmix_report', arguments: { planId: plan.planId, format: 'markdown' } });
  assert.match(markdown.result.content[0].text, /# Unmix task review/);
  assert.equal((await request('tools/call', { name: 'unmix_report', arguments: { planId: plan.planId, format: 'html' } })).result.isError, true);
  const inspected = await tool('unmix_inspect', { planId: plan.planId });
  assert.equal(inspected.status, 'checks_passed');
  const observation = { planId: plan.planId, checkId: 'scroll-position', title: 'Scroll position',
    procedure: 'Fixture-only observation; no real human interaction.', result: 'passed', observer: 'MCP test client',
    note: 'Synthetic API test.', expectedTree: inspected.candidateTree };
  assert.equal(discovery.find(t => t.name === 'unmix_manual_check').annotations.readOnlyHint, false);
  assert.equal((await tool('unmix_manual_check', observation)).state, 'passed');
  fs.writeFileSync(path.join(plan.candidate, 'later.txt'), 'later adaptation');
  assert.equal((await tool('unmix_report', { planId: plan.planId })).manualChecks.state, 'stale');
  assert.equal((await request('tools/call', { name: 'unmix_manual_check', arguments: observation })).result.isError, true);
  assert.equal((await request('tools/call', { name: 'unmix_manual_check', arguments: { ...observation, result: 'maybe' } })).result.isError, true);
  fs.writeFileSync(path.join(plan.candidate, 'base.txt'), 'weakened contract');
  const refused = await tool('unmix_verify', { planId: plan.planId });
  assert.equal(refused.passed, false); assert.equal(refused.skipped, 'protected_inputs_changed');
  assert.equal((await tool('unmix_report', { planId: plan.planId })).protectedInputs.state, 'changed');
  const obligation = { requirementId: 'base-preserved', title: 'Base remains', kind: 'preserve', command: ['node', '-e', "if(require('fs').readFileSync('base.txt','utf8')!=='base')process.exit(1)"] };
  const passportPlan = await tool('unmix_prepare', { remove: ['drop'], instruction: 'Drop temporary file with a passport', requirements: [obligation, { requirementId: 'scroll', title: 'Scroll', kind: 'preserve', checkId: 'scroll', procedure: 'Fixture scroll procedure' }] });
  assert.equal((await tool('unmix_verify', { planId: passportPlan.planId })).passed, false);
  const originalReview = await tool('unmix_verify', { planId: passportPlan.planId, phase: 'baseline' });
  const originalInspection = await tool('unmix_inspect', { planId: passportPlan.planId });
  for (const phase of ['baseline', 'candidate']) await tool('unmix_manual_check', { ...observation, planId: passportPlan.planId, phase, checkId: 'scroll', procedure: 'Fixture scroll procedure', expectedTree: phase === 'baseline' ? originalInspection.baselineReview.tree : originalInspection.candidateTree });
  assert.equal((await tool('unmix_verify', { planId: passportPlan.planId })).passport.ready, true);
  assert.equal(originalReview.phase, 'baseline');
  assert.equal((await request('tools/call', { name: 'unmix_verify', arguments: { planId: passportPlan.planId, phase: 'bad' } })).result.isError, true);
  assert.equal((await request('tools/call', { name: 'unmix_prepare', arguments: { remove: ['drop'], instruction: 'Bad', requirements: [{ ...obligation, command: [] }] } })).result.isError, true);
  const context = { browser: 'FixtureBrowser', browserVersion: '1', environment: 'local', authState: 'signed_out', session: 'fresh-session', dataState: 'seed-v1' };
  const declared = await tool('unmix_manual_context', { planId: passportPlan.planId, context });
  assert.equal(declared.changed, true);
  assert.equal(discovery.find(t => t.name === 'unmix_manual_context').annotations.readOnlyHint, false);
  const contextInspection = await tool('unmix_inspect', { planId: passportPlan.planId });
  assert.equal(contextInspection.manualContexts.candidate.revision, declared.revision);
  assert.equal(contextInspection.passport.ready, false);
  assert.equal((await request('tools/call', { name: 'unmix_manual_check', arguments: { ...observation, planId: passportPlan.planId, expectedTree: contextInspection.candidateTree } })).result.isError, true);
  await tool('unmix_manual_check', { ...observation, planId: passportPlan.planId, expectedTree: contextInspection.candidateTree, expectedContext: declared.revision });
  assert.equal((await request('tools/call', { name: 'unmix_manual_context', arguments: { planId: passportPlan.planId, context: { ...context, cookies: 'forbidden-field' } } })).result.isError, true);
  fs.writeFileSync(path.join(repo, 'checkpoint.txt'), 'completed chunk');
  const checkpoint = await tool('unmix_checkpoint', { title: 'Completed chunk' });
  assert.equal(checkpoint.recordingMode, 'checkpoint');
  assert.equal(checkpoint.intent, 'Completed chunk');
  assert.equal(discovery.find(t => t.name === 'unmix_checkpoint').annotations.readOnlyHint, false);
  const invalid = await request('tools/call', { name: 'unmix_begin', arguments: { taskId: 'x', title: 'x', intent: 'x', repo: '/' } });
  assert.equal(invalid.result.isError, true);
  assert.equal((await request('tools/call', { name: 'missing' })).error.code, -32602);
  assert.equal(stderr, '');
});
